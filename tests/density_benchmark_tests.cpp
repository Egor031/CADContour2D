TEST(DensityData, CancellationStopsWithoutRemovingOtherFiles) {
    QTemporaryDir root; FileIo io; auto marker = root.filePath("user.data"); writeNew(marker,"keep",io);
    auto dir = root.filePath("input"); int calls = 0;
    try { writeInputs(dir,makeSpec("uniform",8,3,1),io,[&] { if (++calls == 2) throw Failure("cancelled","test"); }); FAIL(); }
    catch (const Failure &e) { EXPECT_EQ(e.status,"cancelled"); }
    EXPECT_EQ(readFile(marker,4,io),"keep"); EXPECT_TRUE(QFileInfo::exists(tilePath(dir,0)));
    EXPECT_FALSE(QFileInfo::exists(tilePath(dir,1)));
    EXPECT_THROW(writeInputs(dir,makeSpec("uniform",8,3,1),io,noop),Failure);
}
