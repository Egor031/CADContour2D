TEST(DensityCli, EndToEndSharedInputsAndReadOnlyExternalCache) {
    QTemporaryDir root; const auto dir = root.filePath("smoke");
    auto a = run({"--output-dir",dir,"--repeats","2"}); ASSERT_EQ(a.code,0) << a.error.toStdString();
    auto report = readJson(QDir(dir).filePath("results.json"));
    EXPECT_EQ(report["status"],"ok"); EXPECT_EQ(report["inputs"].toObject()["datasets"].toArray().size(),12);
    auto rows = report["measurements"].toArray(); EXPECT_EQ(rows.size(),130);
    int first = 0, subsequent = 0;
    for (auto v : rows) {
        auto r = v.toObject(); EXPECT_EQ(r["status"],"ok");
        if (r["runClass"] == "first") ++first;
        if (r["runClass"] == "subsequent") ++subsequent;
    }
    EXPECT_EQ(first,50); EXPECT_EQ(subsequent,50); EXPECT_FALSE(report["subsequentStatistics"].toObject().isEmpty());
    EXPECT_EQ(integer(report,"temporaryFilesAfterBytes"),0);
    const auto external = QDir(dir).filePath("boundaries.pc2dcache"); FileIo io;
    const auto before = readFile(external,MiB,io);
    auto b = run({"--output-dir",root.filePath("external"),"--cache",external,"--cell","1",
        "--scenario","empty","--repeats","1"}); ASSERT_EQ(b.code,0) << b.error.toStdString();
    EXPECT_EQ(before,readFile(external,MiB,io));
    auto inputs = readJson(root.filePath("external/inputs.json")); auto rasters = inputs["rasters"].toArray();
    EXPECT_EQ(rasters.size(),7); EXPECT_EQ(rasters.last().toObject()["name"],"external-cache");
    EXPECT_TRUE(rasters.last().toObject()["oracleAvailable"].toBool());
}
