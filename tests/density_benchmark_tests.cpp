TEST(DensityMeasurement, ErrorResourceCancellationAndWrongResultsAreDistinct) {
    QTemporaryDir root;
    for (const auto &status : {"io_error","cancelled","resource_refused"}) {
        auto row = measure("failure","d",root.path(),[&](FileIo &) -> QJsonObject { throw Failure(status,"expected"); });
        EXPECT_EQ(row["status"],status); EXPECT_TRUE(row["correctness"].isNull());
    }
    auto incorrect = measure("wrong","d",root.path(),[](FileIo &) { return QJsonObject{}; },[] { return false; });
    EXPECT_EQ(incorrect["status"],"incorrect");
    auto alloc = measure("alloc","d",root.path(),[](FileIo &) -> QJsonObject { throw std::bad_alloc{}; });
    EXPECT_EQ(alloc["status"],"resource_refused");
    auto cancelled = measure("verify","d",root.path(),[](FileIo &) { return QJsonObject{}; },
        []() -> bool { throw Failure("cancelled","verification cancelled"); });
    EXPECT_EQ(cancelled["status"],"cancelled");
}
