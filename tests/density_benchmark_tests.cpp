auto noop = [] {};
QJsonObject readJson(const QString &path) {
    FileIo io; return QJsonDocument::fromJson(readFile(path, 4 * MiB, io)).object();
}
struct Run { int code; QByteArray error; };
Run run(const QStringList &args) {
    QProcess p; p.start(DENSITY_BENCHMARK_EXE, args);
    if (!p.waitForFinished(50000)) { p.kill(); p.waitForFinished(5000); return {-1, "timeout"}; }
    return {p.exitCode(), p.readAllStandardError()};
}
TEST(DensityData, AllScenariosAreDeterministicAndRoundTrip) {
    QTemporaryDir root; ASSERT_TRUE(root.isValid());
    for (const auto &name : scenarioNames()) {
        auto s = makeSpec(name, 8, 3, 6001);
        EXPECT_EQ(toJson(s), toJson(specFromJson(toJson(s))));
        auto a = fingerprint(s, [&](TileKey k) { return generate(s,k); });
        auto b = fingerprint(s, [&](TileKey k) { return generate(s,k); });
        EXPECT_EQ(a, b);
        FileIo io; auto dir = root.filePath(name);
        writeInputs(dir, s, io, noop);
        FileIo readIo; U64 n = 0, total = 0;
        readInputs(dir, s, {}, [&](const Tile &t) {
            EXPECT_EQ(t, generate(s,t.key)); EXPECT_EQ(t, decode(encode(t)));
            total = add(total, sum(t)); ++n;
        }, readIo, noop);
        EXPECT_EQ(n, tileCount(s)); EXPECT_EQ(total, integer(a,"sum"));
        EXPECT_EQ(readIo.readBytes, inputBytes(s)); EXPECT_EQ(readIo.reads, tileCount(s));
        EXPECT_GT(io.writeBytes, inputBytes(s));
    }
}
TEST(DensityData, LiteralControlValuesAndIndependentSums) {
    EXPECT_EQ(integer(fingerprint(makeSpec("empty",8,3,1), [](TileKey k) { return generate(makeSpec("empty",8,3,1),k); }), "sum"), 0);
    for (const auto &name : {"uniform", "dense"}) {
        auto s = makeSpec(name,8,3,1);
        U64 expected = s.width * s.height * (QString(name) == "uniform" ? 1 : 4096);
        EXPECT_EQ(integer(fingerprint(s,[&](TileKey k) { return generate(s,k); }),"sum"), expected);
    }
    auto h = makeSpec("horizontal",8,3,1), v = makeSpec("vertical",8,3,1);
    auto ht = generate(h,{0,0}), vt = generate(v,{0,0});
    EXPECT_EQ(ht.counts[1],11); EXPECT_EQ(ht.counts[8],0);
    EXPECT_EQ(vt.counts[1],0); EXPECT_EQ(vt.counts[8],13);
    auto overlap = generate(makeSpec("overlap",8,3,1),{0,0});
    EXPECT_EQ(overlap.counts[0],12); EXPECT_EQ(overlap.counts[1],7); EXPECT_EQ(overlap.counts[8],5);
    EXPECT_EQ(generate(makeSpec("u32",8,3,1),{0,0}).counts[0],0xffffffffULL);
    EXPECT_EQ(generate(makeSpec("u64",8,3,1),{0,0}).counts[0],0x100000001ULL);
}
